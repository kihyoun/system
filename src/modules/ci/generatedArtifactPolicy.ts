import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import type { ContextEntry } from './committedContext.service';

// Historical source layouts require their original three generated copies.
// Current source retains only the exact frozen v6 recipe artifact.
const artifacts = Object.freeze([
  'templates/project-bootstrap/wizard-build/typed-v6/runtime/project-ci.cjs',
  'wizard/.gitlab/runtime/project-ci.cjs',
  'wizard/.system-bootstrapper/build-v2/runtime/project-ci.cjs',
]);
const producerPath = 'wizard/.gitlab/producer-v2.json';
// Existing generated bytes retain their original authoring command.
const generators = [
  'operations/' + 'scripts/bundle-project-ci.mjs',
  'node dist/modules/build/bundle-project-ci-entry.js',
  'system-bootstrapper bundle-project-ci',
];
const hash = (bytes: Buffer) => crypto.createHash('sha256').update(bytes).digest('hex');

export function verifiedGeneratedArtifacts(root: string, entries: ContextEntry[]) {
  const committed = new Map(entries.map((entry) => [entry.name, entry]));
  const present = artifacts.filter((name) => committed.has(name));

  if (!present.length) {
    return [];
  }

  const read = (name: string) => {
    const entry = committed.get(name);

    if (!entry || entry.type !== 'blob' || !['100644', '100755'].includes(entry.mode)) {
      throw Error('Portable generated runtime input must be a committed regular file: ' + name);
    }

    const file = path.join(root, name);
    const stat = fs.lstatSync(file);

    if (!stat.isFile() || stat.isSymbolicLink()) {
      throw Error('Portable generated runtime input must be a regular file: ' + name);
    }

    return fs.readFileSync(file);
  };

  if (!committed.has('wizard/.gitlab/producer-v3.json') && present.length !== artifacts.length) {
    throw Error('Portable generated runtime inventory is incomplete.');
  }

  const runtime = read(artifacts[0]);

  if (committed.has('wizard/.gitlab/producer-v3.json')) {
    if (
      present.length !== 1 ||
      hash(runtime) !== 'b93a4461a3ce8733a61ad9159270ab9ced71628578700e715a2c6a022b795a03'
    ) {
      throw Error('Frozen typed-v6 recipe bytes differ.');
    }

    const licensePath = path.posix.join(path.posix.dirname(artifacts[0]), 'LICENSES.txt');
    const license = read(licensePath);

    if (hash(license) !== 'a7a6d4d639a3e6d20b49ba13cf235c495ccc7ed8006137ab8f174952282483b6') {
      throw Error('Frozen typed-v6 recipe license differs.');
    }

    return [
      {
        path: artifacts[0],
        sha256: hash(runtime),
        license: { path: licensePath, sha256: hash(license) },
        producer: 'wizard/.gitlab/producer-v3.json',
        generator: 'immutable node24-vite8-typed-v6 recipe',
      },
    ];
  }

  if (present.length !== artifacts.length) {
    throw Error('Portable generated runtime inventory is incomplete.');
  }

  const generator = generators.find((candidate) =>
    runtime
      .toString('utf8')
      .startsWith('// Generated from compiled shared operations; run ' + candidate + '.\n'),
  );

  if (!generator) {
    throw Error('Portable generated runtime has an unknown generator.');
  }

  for (const name of artifacts.slice(1)) {
    if (!read(name).equals(runtime)) {
      throw Error('Portable generated runtime copies differ.');
    }
  }
  const runtimeSha256 = hash(runtime);
  const value: unknown = JSON.parse(read(producerPath).toString('utf8'));

  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw Error('Portable generated runtime producer identity is invalid.');
  }

  const producer = value as Record<string, unknown>;

  if (
    producer.version !== 2 ||
    producer.runtime !== '.gitlab/runtime/project-ci.cjs' ||
    producer.buildProfile !== 'node24-vite8-typed-v6' ||
    producer.runtimeSha256 !== runtimeSha256
  ) {
    throw Error('Portable generated runtime producer identity or SHA-256 differs.');
  }

  const licenses = artifacts.map((name) =>
    path.posix.join(path.posix.dirname(name), 'LICENSES.txt'),
  );
  const license = read(licenses[0]);

  if (
    !license
      .toString('utf8')
      .startsWith('Bundled project CI runtime licenses\n\nSystem Bootstrapper\n')
  ) {
    throw Error('Portable generated runtime license notice is missing.');
  }

  for (const name of licenses.slice(1)) {
    if (!read(name).equals(license)) {
      throw Error('Portable generated runtime license copies differ.');
    }
  }
  return artifacts.map((name, index) => ({
    path: name,
    sha256: runtimeSha256,
    license: { path: licenses[index], sha256: hash(license) },
    producer: producerPath,
    generator,
  }));
}
