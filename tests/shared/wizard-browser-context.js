'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const crypto = require('crypto');
const {execFileSync} = require('child_process');
const {pack} = require('../../project-bootstrap/wizard-source/package');
const {prepareWizardBrowser} = require('../prepare-wizard-browser');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'wizard-browser-context-'));
const selectors = {SYSTEM_SOURCE_GIT_DIR:process.env.SYSTEM_SOURCE_GIT_DIR, WIZARD_SOURCE_GIT_DIR:process.env.WIZARD_SOURCE_GIT_DIR};
delete process.env.SYSTEM_SOURCE_GIT_DIR; delete process.env.WIZARD_SOURCE_GIT_DIR;
const write = (name, data) => { const filename = path.join(root, name); fs.mkdirSync(path.dirname(filename), {recursive:true}); fs.writeFileSync(filename, data); };
const git = (cwd, ...args) => execFileSync('git', ['-C', cwd, ...args], {stdio:['ignore', 'pipe', 'pipe']}).toString().trim();
const init = cwd => { git(cwd, 'init'); git(cwd, 'config', 'user.name', 'Fixture'); git(cwd, 'config', 'user.email', 'fixture@example.invalid'); };
try {
  init(root);
  for (const [name, data] of Object.entries({'package.json':'{}', 'package-lock.json':'{}', 'src/api/Helper.tsx':'public', '.gitlab-ci.yml':'stages: [test]', 'playwright.config.ts':'native config', 'tests/browser/public.spec.ts':'native suite', 'tests/browser/run.sh':'#!/bin/sh\n', 'private.env':'never copied', '.system-bootstrapper/build-v1/reserved':'never copied'})) write('wizard/'+name, data);
  const binary = Buffer.from([0, 255, 128, 13, 10]); write('wizard/public/image.png', binary);
  const wizard = path.join(root, 'wizard'); init(wizard);
  git(wizard, 'add', '.'); git(wizard, 'update-index', '--chmod=+x', 'tests/browser/run.sh'); git(wizard, 'commit', '-m', 'Source');
  const wizardRevision = git(wizard, 'rev-parse', 'HEAD');
  write('tests/wizard-browser.Dockerfile', 'FROM scratch\n');
  const trust = ['bootstrapper/refresh-ca.sh', 'bootstrapper/ca/cacert-2026-10-20.crt', 'bootstrapper/ca/provenance.json', 'bootstrapper/ca/check.js'];
  const trustContents = new Map(trust.map(name => [name, fs.readFileSync(path.join(__dirname, '../..', name))]));
  for (const [name, content] of trustContents) write(name, content);
  write('bootstrapper/ca/operator-private.pem', 'committed private CA must not enter');
  write('bootstrapper/unrelated-host-file', 'unrelated host file must not enter');
  git(root, 'add', 'tests', 'bootstrapper'); git(root, 'update-index', '--chmod=+x', 'bootstrapper/refresh-ca.sh');
  git(root, 'update-index', '--add', '--cacheinfo', '160000,'+wizardRevision+',wizard'); git(root, 'commit', '-m', 'System');
  const snapshot = pack(root);
  write('project-bootstrap/wizard-source/snapshot.json', JSON.stringify({...snapshot, unknownPrivateMetadata:'must not enter'}));
  write('tests/wizard-browser.Dockerfile', 'dirty private recipe'); write('wizard/tests/browser/public.spec.ts', 'dirty browser suite'); write('wizard/untracked-secret', 'private');
  for (const name of trust) write(name, 'dirty unreviewed host trust');
  const result = prepareWizardBrowser(root);
  const archive = path.join(root, '.wizard-browser-context/context.tar');
  const read = name => execFileSync('tar', ['-xOf', archive, name]);
  assert.equal(read('tests/wizard-browser.Dockerfile').toString(), 'FROM scratch\n');
  assert.equal(read('wizard/tests/browser/public.spec.ts').toString(), 'native suite');
  assert(read('wizard/public/image.png').equals(binary));
  assert(execFileSync('tar', ['-tvf', archive, 'wizard/tests/browser/run.sh'], {encoding:'utf8'}).includes('rwxr-xr-x'));
  for (const [name, content] of trustContents) assert(read(name).equals(content), 'use the exact committed public trust input: '+name);
  assert.equal(crypto.createHash('sha256').update(read('bootstrapper/ca/cacert-2026-10-20.crt')).digest('hex'), '796f1389bfea13c0ed78f663b765baaff54a508e5483786bd6ece73c5e3e3cbe');
  assert(execFileSync('tar', ['-tvf', archive, 'bootstrapper/refresh-ca.sh'], {encoding:'utf8'}).includes('rwxr-xr-x'));
  assert.deepEqual(result.files.filter(name => name.startsWith('bootstrapper/')).sort(), trust.slice().sort(), 'exact public trust allowlist excludes even committed host/private files');
  assert(!result.files.some(name => /private\.env|reserved|untracked-secret|snapshot\.json|\.git\//.test(name)));
  assert.equal(result.wizardRevision, wizardRevision);
  assert.equal(result.checksum, crypto.createHash('sha256').update(fs.readFileSync(archive)).digest('hex'));
  assert.equal(fs.readFileSync(path.join(root, '.wizard-browser-context/revision'), 'utf8').trim(), git(root, 'rev-parse', 'HEAD'));
  const forged = JSON.parse(JSON.stringify(snapshot));
  const file = forged.files.find(item => item.path === 'tests/browser/public.spec.ts'); file.content = Buffer.from('forged suite').toString('base64'); file.sha256 = crypto.createHash('sha256').update(Buffer.from(file.content, 'base64')).digest('hex');
  forged.manifestHash = crypto.createHash('sha256').update(JSON.stringify({version:forged.version, sourceRevision:forged.sourceRevision, files:forged.files.map(({path, mode, sha256}) => ({path, mode, sha256}))})).digest('hex');
  write('project-bootstrap/wizard-source/snapshot.json', JSON.stringify(forged));
  assert.throws(() => prepareWizardBrowser(root), /differs from committed source/);
  write('project-bootstrap/wizard-source/snapshot.json', JSON.stringify(snapshot));
  const trustBlob = git(root, 'rev-parse', 'HEAD:bootstrapper/ca/check.js');
  git(root, 'update-index', '--cacheinfo', '120000,'+trustBlob+',bootstrapper/ca/check.js'); git(root, 'commit', '-m', 'Refuse trust links');
  assert.throws(() => prepareWizardBrowser(root), /committed regular file/);
  git(root, 'update-index', '--cacheinfo', '100644,'+trustBlob+',bootstrapper/ca/check.js'); git(root, 'commit', '-m', 'Restore trust blob');
  git(root, 'rm', '--cached', 'bootstrapper/ca/provenance.json'); git(root, 'commit', '-m', 'Refuse missing trust');
  assert.throws(() => prepareWizardBrowser(root), /committed regular file/);
  const second = 'b'.repeat(40); git(root, 'update-index', '--cacheinfo', '160000,'+second+',wizard'); git(root, 'commit', '-m', 'Changed pin');
  assert.throws(() => prepareWizardBrowser(root), /match the committed/);
  console.log('PASS: browser context preserves committed full suite, exact reviewed public trust, executable/binary inputs and provenance; excludes dirty/private/reserved files and rejects forged/stale snapshots, trust links and missing trust inputs.');
} finally {
  fs.rmSync(root, {recursive:true, force:true});
  for (const [key, value] of Object.entries(selectors)) { if (value === undefined) delete process.env[key]; else process.env[key] = value; }
}
